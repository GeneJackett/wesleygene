-- init.sql
CREATE DATABASE IF NOT EXISTS personal_website_db;
USE personal_website_db;

CREATE TABLE IF NOT EXISTS blogs (
    id INT AUTO_INCREMENT PRIMARY KEY UNIQUE,
    category VARCHAR(255) NOT NULL,
    blogTitle VARCHAR(255) NOT NULL,
    blogSummary TEXT NOT NULL,
    blogContent LONGTEXT NOT NULL,
    blog_last_update TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    blog_create_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
